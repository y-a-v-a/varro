#!/usr/bin/env python3
"""Regenerate site/data.js from the repository's own records.

The site states nothing numeric by hand. Every figure it shows is read from a
file the pipeline already writes, so the page cannot drift a build behind the
way transcribed tables do:

    manifest/sources.yaml          which sources exist, licence, tier, period
    ATTRIBUTION*.md                what each source contributed to each corpus
    data/processed/*.summary.json  corpus totals and the period breakdown
    data/processed/token-growth.json   token counts per corpus
    reports/train-*.json           every model's configuration and loss curve
    reports/memorization-*.json    the recitation measurements
    reports/baselines-*.json       bigram floors

plus the two hand-edited files that hold words rather than numbers:

    site/content/models.yaml       the model versions and what they showed
    site/content/sources.yaml      a public one-liner per source

data/ is gitignored, so on a machine without a built corpus the corpus block is
carried over from the existing data.js rather than dropped — say so, and move on.

    python site/tools/sync.py           write site/data.js
    python site/tools/sync.py --check   exit 1 if site/data.js is out of date
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

import yaml

SITE = Path(__file__).resolve().parents[1]
ROOT = SITE.parent
OUT = SITE / "data.js"

REPO_URL = "https://github.com/y-a-v-a/varro"
PREFIX = "// Generated by site/tools/sync.py — do not edit by hand.\nwindow.VARRO = "

# Which attribution notice describes which corpus.
ATTRIBUTIONS = {
    "corpus": "ATTRIBUTION.md",
    "classical": "ATTRIBUTION-classical.md",
    "corpus-b": "ATTRIBUTION-corpus-b.md",
}

CORPUS_LABELS = {
    "corpus": ("A", "Track A · full"),
    "classical": ("A", "Track A · classical"),
    "corpus-b": ("B", "Track B · full"),
    "classical-b": ("B", "Track B · classical"),
}

LICENCE_URLS = {
    "CC-BY-SA-4.0": "https://creativecommons.org/licenses/by-sa/4.0/",
    "CC-BY-4.0": "https://creativecommons.org/licenses/by/4.0/",
    "CC-BY-3.0": "https://creativecommons.org/licenses/by/3.0/",
    "CC-BY-NC-SA-4.0": "https://creativecommons.org/licenses/by-nc-sa/4.0/",
    "CC-BY-NC-SA-3.0": "https://creativecommons.org/licenses/by-nc-sa/3.0/",
    "UB-Public-License-1.0": "https://cse.buffalo.edu/sneps/ubpl.pdf",
}


def load_yaml(path: Path) -> dict:
    with path.open(encoding="utf-8") as fh:
        return yaml.safe_load(fh) or {}


def load_json(path: Path):
    with path.open(encoding="utf-8") as fh:
        return json.load(fh)


# --------------------------------------------------------------------------
# attribution notices
# --------------------------------------------------------------------------

CONTRIBUTION = re.compile(
    r"Contribution:\s*([\d,]+) words across ([\d,]+) documents \(([\d.]+)% of the corpus\)"
)


def parse_attribution(path: Path) -> dict:
    """Read one ATTRIBUTION*.md into totals plus per-source contributions.

    The notices are generated by provenance.py in a fixed shape, which is what
    makes reading them back safe. A notice that no longer parses is an error
    rather than an empty section on the page.
    """
    text = path.read_text(encoding="utf-8")

    def field(label: str) -> str | None:
        m = re.search(rf"\*\*{label}\*\*:\s*`?([^`\n]+)`?", text)
        return m.group(1).strip() if m else None

    sources = {}
    for block in re.split(r"^### ", text, flags=re.M)[1:]:
        name, _, body = block.partition("\n")
        m = CONTRIBUTION.search(body)
        if not m:
            raise SystemExit(f"{path.name}: no contribution line under '{name}'")
        version = re.search(r"Version ingested:\s*`([^`]+)`", body)
        sources[name.strip()] = {
            "words": int(m.group(1).replace(",", "")),
            "documents": int(m.group(2).replace(",", "")),
            "share": float(m.group(3)),
            "version": version.group(1) if version else None,
        }
    if not sources:
        raise SystemExit(f"{path.name}: no sources found — has its format changed?")

    generated = re.search(r"on (\d{4}-\d{2}-\d{2})", text)
    return {
        "documents": int((field("Documents") or "0").replace(",", "")),
        "words": int((field("Words") or "0").replace(",", "")),
        "licence": field("Effective licence of the assembled corpus"),
        "generated": generated.group(1) if generated else None,
        "sources": sources,
    }


# --------------------------------------------------------------------------
# sources
# --------------------------------------------------------------------------

def source_group(src: dict, contributes: bool) -> str:
    """Where a source sits on the page. Derived, like track membership is."""
    tier, include = src.get("tier"), src.get("include", False)
    if tier == "eval":
        return "eval"
    if tier == "green" and include and contributes:
        return "track-a"
    if tier == "amber" and include and contributes:
        return "track-b"
    return "pending"


def build_sources(attributions: dict) -> list[dict]:
    manifest = load_yaml(ROOT / "manifest" / "sources.yaml")
    blurbs = load_yaml(SITE / "content" / "sources.yaml").get("sources", {}) or {}

    out = []
    for src in manifest["sources"]:
        extra = blurbs.get(src["id"], {}) or {}
        if extra.get("hidden"):
            continue
        contributions = {
            corpus: att["sources"][src["name"]]
            for corpus, att in attributions.items()
            if src["name"] in att["sources"]
        }
        licence = str(src.get("license", "unknown"))
        out.append({
            "id": src["id"],
            "name": src["name"],
            "url": src.get("url"),
            "licence": licence,
            "licence_url": LICENCE_URLS.get(licence),
            "tier": src.get("tier"),
            "include": bool(src.get("include")),
            "period": src.get("period"),
            "format": src.get("format"),
            "text_provenance": src.get("text_provenance"),
            "blurb": extra.get("blurb"),
            "group": source_group(src, bool(contributions)),
            "contributions": contributions,
        })
    # Largest contribution first within each group; declared order otherwise.
    order = {s["id"]: i for i, s in enumerate(out)}

    def weight(s):
        best = max((c["words"] for c in s["contributions"].values()), default=0)
        return (-best, order[s["id"]])

    return sorted(out, key=weight)


# --------------------------------------------------------------------------
# corpora
# --------------------------------------------------------------------------

def build_corpora(attributions: dict, previous: dict | None) -> dict:
    processed = ROOT / "data" / "processed"
    growth_path = processed / "token-growth.json"
    summaries = sorted(processed.glob("*.summary.json"))
    if not summaries:
        if previous and previous.get("corpora"):
            print("  data/processed/ has no summaries — keeping the corpus figures "
                  "already in data.js", file=sys.stderr)
            return previous["corpora"]
        raise SystemExit("no data/processed/*.summary.json and no previous data.js to fall back on")

    tokens = {}
    if growth_path.exists():
        tokens = {row["name"]: row["train_tokens"] for row in load_json(growth_path)}

    corpora = {}
    for path in summaries:
        name = path.name.removesuffix(".summary.json")
        if name not in CORPUS_LABELS:
            continue
        s = load_json(path)
        track, label = CORPUS_LABELS[name]
        att = attributions.get(name)
        corpora[name] = {
            "label": label,
            "track": track,
            "records": s["records"],
            "words": s["words"],
            "train_tokens": tokens.get(name),
            "periods": s.get("periods", {}),
            "text_provenance": s.get("text_provenance", {}),
            "redistributable": s.get("redistributable"),
            "licence": att["licence"] if att else None,
        }
    return corpora


# --------------------------------------------------------------------------
# models
# --------------------------------------------------------------------------

def floor_for(report: dict) -> float | None:
    """A bigram floor, but only one measured on the very same text.

    The same rule compare.py applies: a corpus keeps its name across rebuilds,
    so a floor counts only when the corpus description and the tokenizer both
    match the run's. Anything older has to state its floor in models.yaml.
    """
    path = ROOT / "reports" / f"baselines-{report.get('corpus_name')}.json"
    if not path.exists() or "corpus" not in report or "tokenizer" not in report:
        return None
    base = load_json(path)
    if base.get("corpus") != report["corpus"]:
        return None
    if base.get("tokenizer", {}).get("sha256") != report["tokenizer"].get("sha256"):
        return None
    return round(base["baselines"]["overall_perplexity"], 2)


def build_run(entry: dict) -> dict:
    run = entry["run"]
    report = load_json(ROOT / "reports" / f"train-{run}.json")
    cfg = report["config"]
    per_step = cfg["batch"] * cfg["context"]
    train_tokens = report["train_tokens"]

    history = [
        [
            round(h["step"] * per_step / train_tokens, 4),   # epoch
            h["step"] * per_step,                              # tokens seen
            round(h["val_perplexity"], 2),
        ]
        for h in report["history"]
    ]

    final = report["final"]
    floor = entry.get("floor") or floor_for(report)
    out = {
        "run": run,
        "role": entry.get("role", "single"),
        "headline": bool(entry.get("headline")),
        "curve": "hidden" if entry.get("curve") == "hidden" else bool(entry.get("curve")),
        "date": report["generated"][:10],
        "corpus": report.get("corpus_name", cfg.get("corpus")),
        "init_from": cfg.get("init_from"),
        "parameters": report["parameters"],
        "dim": cfg["dim"],
        "layers": cfg["layers"],
        "heads": cfg["heads"],
        "context": cfg["context"],
        "vocab": cfg.get("vocab"),
        "train_tokens": train_tokens,
        "tokens_seen": final["step"] * per_step,
        "epochs": round(report["epochs"], 2),
        "perplexity": round(final["val_perplexity"], 2),
        "hours": round(final["elapsed_s"] / 3600, 1),
        "floor": floor,
        "x_floor": round(floor / final["val_perplexity"], 2) if floor else None,
        "history": history,
    }

    memo_path = ROOT / "reports" / f"memorization-{run}.json"
    if memo_path.exists():
        memo = load_json(memo_path)
        out["memorization"] = {
            "window": memo["window"],
            "windows": memo["memorization"]["windows"],
            "memorised": memo["memorization"]["memorised"],
            "longest": memo["memorization"]["longest_verbatim_words"],
            "curve": [
                [int(n), round(v["text"], 4), round(v["control"], 4)]
                for n, v in sorted(memo["curve"].items(), key=lambda kv: int(kv[0]))
            ],
        }
    return out


def build_models() -> list[dict]:
    content = load_yaml(SITE / "content" / "models.yaml")
    models = []
    for m in content["models"]:
        runs = [build_run(r) for r in m["runs"]]
        headline = next((r for r in runs if r["headline"]), runs[-1])
        date = m.get("date")
        models.append({
            "id": m["id"],
            "name": m["name"],
            "numeral": m.get("numeral"),
            "date": str(date) if date else headline["date"],
            "status": m.get("status"),
            "track": m.get("track"),
            "link": m.get("link"),
            "summary": " ".join(str(m.get("summary", "")).split()),
            "notes": m.get("notes", []),
            "runs": runs,
        })
    return models


# --------------------------------------------------------------------------

def read_previous() -> dict | None:
    if not OUT.exists():
        return None
    text = OUT.read_text(encoding="utf-8")
    body = text.split("window.VARRO = ", 1)[-1].rstrip().rstrip(";")
    try:
        return json.loads(body)
    except json.JSONDecodeError:
        return None


def build() -> str:
    attributions = {
        corpus: parse_attribution(ROOT / name)
        for corpus, name in ATTRIBUTIONS.items()
        if (ROOT / name).exists()
    }
    models = build_models()
    data = {
        "repo": REPO_URL,
        "attribution_generated": max(
            (a["generated"] for a in attributions.values() if a["generated"]), default=None
        ),
        "reports_generated": max(r["date"] for m in models for r in m["runs"]),
        "corpora": build_corpora(attributions, read_previous()),
        "sources": build_sources(attributions),
        "models": models,
    }
    return PREFIX + json.dumps(data, indent=1, ensure_ascii=False) + ";\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true",
                    help="write nothing; exit 1 if site/data.js differs from what would be generated")
    args = ap.parse_args()

    text = build()
    current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
    if args.check:
        if text != current:
            print("site/data.js is out of date — run: python site/tools/sync.py")
            return 1
        print("site/data.js is up to date")
        return 0
    if text == current:
        print("site/data.js already up to date")
    else:
        OUT.write_text(text, encoding="utf-8")
        print(f"wrote {OUT.relative_to(ROOT)} ({len(text):,} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
